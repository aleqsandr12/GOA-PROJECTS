#კომენტარების სახით ახსენი რომელ მონაცემთა ტიპებთან შეგვიძლია გამოვიყენოთ გარკვეული შედარების ოპერატორები


# 1. რიცხვები (int, float) — ყველა შედარების ოპერატორის გამოყენება შესაძლებელია.
a = 5
b = 3.5

print(a == b)    # False — ამოწმებს თანასწორობას
print(a != b)    # True  — ამოწმებს არათანასწორობას
print(a > b)     # True  — რიცხვებით შედარება
print(a <= b)    # False

# 2. სტრინგები (str) — შესაძლებელია ==, !=, <, > და სხვ. სიმბოლოების მიხედვით შედარება (ლექსიკურად).
s1 = "apple"
s2 = "banana"

print(s1 == s2)   # False — სიტყვები განსხვავდება
print(s1 < s2)    # True  — "apple" < "banana" ლექსიკურად, რადგან 'a' < 'b'

# 3. ლოგიკური ტიპები (bool) — True ქცევა აქვს როგორც 1-ს, ხოლო False-ს როგორც 0-ს.
print(True == 1)  # True
print(False < True)  # True — 0 < 1

# 4. სიები (list), tuples, და სხვა კოლექციები — == და != მუშაობს ელემენტების მიხედვით.
list1 = [1, 2, 3]
list2 = [1, 2, 3]
list3 = [3, 2, 1]

print(list1 == list2)  # True — ელემენტები და რიგითობა იდენტურია
print(list1 == list3)  # False — ელემენტები არ ემთხვევა

# <, > ტიპის შედარება სიებს შორის შესაძლებელია მხოლოდ მაშინ,
# როცა ყველა ელემენტი შედარებადია და python-ის წესებით შედარება მკაფიოა.
print([1, 2] < [1, 3])  # True — პირველ განსხვავებულ ელემენტს ადარებს (2 < 3)

# 5. dictionaries (dict) — შესაძლებელია == და !=, მაგრამ < ან > არა.
dict1 = {"a": 1, "b": 2}
dict2 = {"a": 1, "b": 2}
dict3 = {"a": 2, "b": 3}

print(dict1 == dict2)  # True — კლავიშები და მნიშვნელობები იდენტურია
print(dict1 != dict3)  # True — მნიშვნელობები განსხვავდება

# dict1 < dict2 — ეს არ შეიძლება, გამოიწვევს TypeError-ს
# Python არ იძლევა ორი ლექსიკონის ზომიერ შედარებას < ან >

# 6. None ტიპი — == და != მუშაობს, მაგრამ <, > და სხვ. შედარებები გამოიწვევს შეცდომას.
x = None
print(x == None)    # True — თუმცა რეკომენდებულია 'is' გამოიყენოთ: x is None
# print(x < 5)      # გამოიწვევს TypeError-ს

# 7. განსხვავებული ტიპების შედარება (მაგ: str და int) — == და != იმუშავებს, მაგრამ სხვები არა.
print("5" == 5)     # False — ტიპები განსხვავდება
# print("5" < 6)    # TypeError — არ შეიძლება სტრინგისა და რიცხვის შედარება <
