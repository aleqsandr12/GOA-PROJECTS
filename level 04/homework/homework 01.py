#კომენტარების სახით ახსენი რა განსხვავებაა and და or ლოგიკურ ოპერატორებს შორის და რა თვისებები გააჩნიათ



a = 5
b = 10
c = 15

# -------------------------------
# AND ოპერატორი:
# -------------------------------
# 'and' ამოწმებს ორივე პირობას და აბრუნებს True-ს მხოლოდ მაშინ,
# როდესაც ორივე პირობა არის True.
# თუ რომელიმე პირობა False-ია, საბოლოო შედეგიც იქნება False.

if a < b and b < c:  # ორივე პირობა მართალია (True and True)
    print("and: ორივე პირობა შესრულდა")  # დაიბეჭდება ეს

if a > b and b < c:  # პირველი პირობა მცდარია (False and True)
    print("ეს არ დაიბეჭდება")  # შედეგი False იქნება, არაფერი გამოვა

# -------------------------------
# OR ოპერატორი:
# -------------------------------
# 'or' ოპერატორი აბრუნებს True-ს მაშინაც კი, 
# თუ ერთი პირობა მაინც მართალია.
# მხოლოდ მაშინ აბრუნებს False-ს, როცა ორივე პირობაა მცდარი.

if a > b or b < c:  # ერთი პირობა მართალია (False or True)
    print("or: ერთ-ერთი პირობა მაინც შესრულდა")  # დაიბეჭდება ეს

if a > b or c < b:  # ორივე პირობა მცდარია (False or False)
    print("ეს არ დაიბეჭდება")  # შედეგი False იქნება

# -------------------------------
# დამატებითი თვისებები:
# -------------------------------
# 'and' ოპერატორი სტოპდება მაშინვე, როცა პოულობს False-ს.
# 'or' ოპერატორი სტოპდება მაშინვე, როცა პოულობს True-ს.
# ამას ეწოდება "short-circuit evaluation" — ანუ წაკითხვის შეწყვეტა.

# მაგალითი AND-ისთვის:
# თუ პირველი პირობა False-ია, მეორე აღარ მოწმდება.
def check():
    print("ეს ფუნქცია არ გამოიძახება")
    return True

if False and check():
    print("ეს არ დაიბეჭდება")

# მაგალითი OR-ისთვის:
# თუ პირველი პირობა True-ია, მეორე აღარ მოწმდება.
if True or check():
    print("მხოლოდ პირველი პირობით შემოიფარგლება")  # ფუნქცია არ გამოიძახება
