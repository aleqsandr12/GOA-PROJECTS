#მომხმარებელს შემოატანინეთ ორი რიცხვი და დაბეჭდეთ უფრო მაღალი რიცხვი




num1 = int(input("შეიყვანე პირველი რიცხვი: "))
num2 = int(input("შეიყვანე მეორე რიცხვი: "))

if num1 > num2:
    print("უფრო მაღალია:", num1)
elif num2 > num1:
    print("უფრო მაღალია:", num2)
else:
    print("ორივე რიცხვი ტოლია.")
