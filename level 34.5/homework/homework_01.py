#1)
#Indexing (ინდექსი) → კონკრეტული ელემენტის ამოღება მისი ადგილის (ინდექსის) მიხედვით.
#მაგ:

my_list = [10, 20, 30, 40]
print(my_list[1])   # გამოიტანს 20-ს


#აქ [1] ნიშნავს მხოლოდ ერთ კონკრეტულ ელემენტს.

#Slicing (სლაისი) → სიიდან რამდენიმე ელემენტის ამოღება დიაპაზონის მიხედვით.
#მაგ:

my_list = [10, 20, 30, 40, 50]
print(my_list[1:4])   # გამოიტანს [20, 30, 40]


#აქ [1:4] ნიშნავს ინდექსი 1-დან (ჩათვლით) ინდექს 4-მდე (გამომრიცხველად).

#👉 განსხვავება ისაა, რომ index ერთი ელემენტს აბრუნებს, ხოლო slice — რამდენიმე ელემენტს (ქვე-სიას).
