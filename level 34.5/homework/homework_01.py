#count(x) --> ითვლის, რამდენჯერ არის x სიაში.

#upper() - გადააქცევს პატარა ასოებს დიდ ასოებად

#lower() - დიდ ასოებს გადააქცევს პატარა ასოებად

#capitalize() - პირველი ასოს გადავაქცევთ დიდ ასოდ,დანარჩენი ასოები ქინება პატარა ანუ დააპატარავებს

#find() - სტრინგში მნიშვნელობის მოძებნა და მისი ინდექსის დაპრინტვა
#----------------------------------------------------------------------------------------------------------------------#
#3)
#print() --> ეკრანზე გამოაქვს ინფორმაცია, მაგრამ პროგრამას ვერ იყენებს შედეგს.

def test():
    print("Hello")
test()   # ეკრანზე გამოჩნდება Hello


#return --> ფუნქცია აბრუნებს მნიშვნელობას უკან, რომლის გამოყენებაც შეიძლება პროგრამაში.

def test1():
    return "Hello"
word = test1()
print(word)   # Hello


#👉 განსხვავება: print() მხოლოდ აჩვენებს, ხოლო return აბრუნებს, რომ მერე პროგრამამ გამოიყენოს.
