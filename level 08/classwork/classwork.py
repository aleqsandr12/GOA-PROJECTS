#კომენტარის სახით ამიხსენი რა არის control flow
# Control flow (სამართავი ნაკადი) ნიშნავს პროგრამაში იმ გზას, რომლის მიხედვითაც ინსტრუქციები სრულდება.
# ჩვეულებრივ, პროგრამა ზედიზედ ასრულებს კოდს ზემოდან ქვემოთ, მაგრამ control flow-ს საშუალებით
# შეგვიძლია ვაკონტროლოთ, რომელი კოდი როდის შესრულდეს.

# Control flow მოიცავს:
# 1. პირობით სტრუქტურებს (if, else) — გადაწყვეტილების მიღებისთვის
# 2. ციკლებს (for, while) — კოდის განმეორებით შესასრულებლად


# მაგალითად:
x = 5

if x > 0:
    # თუ პირობა ჭეშმარიტია, ეს კოდი შესრულდება
    print("დადებითია")
else:
    # წინააღმდეგ შემთხვევაში შესრულდება ეს
    print("არ არის დადებითი")

# ეს არის control flow-ს ერთ-ერთი მაგალითი — განსაზღვრავს, რომელი კოდი უნდა შესრულდეს კონკრეტულ სიტუაციაში.
