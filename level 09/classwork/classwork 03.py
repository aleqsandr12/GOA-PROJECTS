# ვიწყებთ ცვლადის გამოცხადებით და ვანიჭებთ მნიშვნელობას 1
i = 1

# while ციკლი აგრძელებს მუშაობას მანამ, სანამ პირობა სიმართლეა (True)
while i <= 5:
    # დაბეჭდავს i-ის მიმდინარე მნიშვნელობას
    print(i)
    
    # i-ს მნიშვნელობა იზრდება ერთით ყოველ იტერაციაზე
    i += 1

# როცა i გახდება 6, პირობა i <= 5 იქნება False და ციკლი შეწყდება
