#კომენტარის სახით ახსენით თუ რა განსხვავებაა for loop-სა და while loop-ს შორის 
# ----------------------------------------
# For loop (ციკლი)
# ----------------------------------------
# - გამოიყენება, როცა ვიცით რამდენჯერ უნდა 반복დეს ციკლი.
# - მაგალითად, ციკლი 5-ჯერ ან 10-ჯერ უნდა იწარმოოს.
# - "for" ციკლი ავტომატურად გადის გამეორებადი რიცხვების ან ელემენტების სერიაზე (მაგ. სია, range).
# - უფრო "მექანიკურია" და ნაკლებად დაუცველია შეცდომისგან.

# მაგალითი:
for i in range(5):
    print(i)


# ----------------------------------------
# While loop (ციკლი)
# ----------------------------------------
# - გამოიყენება, როცა არ ვიცით წინასწარ რამდენჯერ გაიმეორებს ციკლი.
# - "while" ციკლი მუშაობს მანამ, სანამ პირობა არის სიმართლე (True).
# - აუცილებელია ზუსტად მართოთ პირობა, რათა ციკლი არ გახდეს უსასრულო.
# - უფრო მოქნილია შემთხვევებისთვის, როცა რეპეტიციის რაოდენობა დამოკიდებულია შედეგზე.

# მაგალითი:
count = 0
while count < 5:
    print(count)
    count += 1
