#მოიყვანეთ while loop-ის მაგალითი და კომენტარის სახით ახსენით, თუ როგორ მუშაობს while ციკლი

# while ციკლი იმეორებს კოდს იმდენჯერ, რამდენჯერაც პირობა არის True

count = 0  # ვქმნით ცვლადს count და ვანიჭებთ 0-ს

while count < 5:  # სანამ count ნაკლებია 5-ზე, შევასრულებთ ციკლის სხეულს
    print("ამოვიდა count =", count)  # დაბეჭდავს текსტს და count-ს მნიშვნელობას
    count += 1  # count-ს მოვამატებთ 1-ს, რათა ციკლი პროგრესირდეს და ერთხელ მაინც შეწყდეს

# როცა count გახდება 5, პირობა (count < 5) იქნება False და ციკლი შეწყდება
