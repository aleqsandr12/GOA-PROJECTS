#გამოიყენე ყველა მათემატიკური ოპერაცია რაც ვისწავლეთ (+,-,*,/)


# ცვლადების განსაზღვრა
a = 10
b = 5

# ყველა მათემატიკური ოპერაცია
addition = a + b         # მიმატება
subtraction = a - b      # გამოკლება
multiplication = a * b   # გამრავლება
division = a / b         # გაყოფა (მცურავი წერტილით)

# შედეგების დაბეჭდვა
print("მიმატება:", addition)
print("გამოკლება:", subtraction)
print("გამრავლება:", multiplication)
print("გაყოფა:", division)
