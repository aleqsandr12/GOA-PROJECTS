a = 20
b = 4
c = 7
d = 3
e = 10
f = 2
g = 5
h = 8


a += b * c          
b -= d + f          
c *= g - h          
d /= f              
e = (a + b) / (c + 1)  
f = g * (h - b)       
g += h * 2            
h = (a + e - d) * 0.5  


print("a =", a)
